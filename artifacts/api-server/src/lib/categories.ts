export interface CatalogTitleData {
  id: string;
  slug: string;
  name: string;
  kind: "movie" | "series" | "live";
  synopsis: string;
  year?: number | null;
  rating?: string | null;
  score: number;
  genres: string[];
  cast?: string[];
  creatorAttribution?: string | null;
  posterUrl?: string | null;
  backdropUrl?: string | null;
  featured?: boolean;
}

