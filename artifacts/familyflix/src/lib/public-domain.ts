export const toCatalogTitle = (film: PublicDomainFilm): {
  slug: string; name: string; tagline: string; year: number; type: "movie";
  rating: string; score: number; duration: string; genres: string[];
  synopsis: string; cast: string[]; creator: string; image: string;
  palette: [string, string]; badge?: string; featured?: boolean;
} => ({
  slug: film.slug,
  name: film.name,
  tagline: film.tagline,
  year: film.year,
  type: "movie",
  rating: film.rating,
  score: film.score,
  duration: film.duration,
  genres: film.genres,
  synopsis: film.synopsis,
  cast: film.cast,
  creator: film.creator,
  image: film.image,
  palette: film.palette,
  ...(film.badge ? { badge: film.badge } : {}),
  ...(film.featured ? { featured: true } : {}),
});
